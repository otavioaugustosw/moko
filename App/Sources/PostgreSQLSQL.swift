import Foundation

enum PostgreSQLSQL {
    static let types = [
        "smallint", "integer", "bigint", "numeric", "real", "double precision", "boolean", "varchar",
        "char", "text", "bytea", "date", "time", "timetz", "timestamp", "timestamptz", "interval",
        "uuid", "json", "jsonb", "inet", "cidr", "macaddr", "bit", "varbit", "text[]", "integer[]",
    ]
    static func identifier(_ value: String) -> String {
        "\"" + value.replacingOccurrences(of: "\"", with: "\"\"") + "\""
    }
    static func literal(_ value: String) -> String { "'" + value.replacingOccurrences(of: "'", with: "''") + "'" }
    static func qualified(_ schema: String, _ name: String) -> String { identifier(schema) + "." + identifier(name) }
    static let databases = "SELECT datname FROM pg_database WHERE datallowconn AND NOT datistemplate ORDER BY datname"
    static let schemas =
        "SELECT nspname FROM pg_namespace WHERE nspname NOT LIKE 'pg_%' AND nspname <> 'information_schema' ORDER BY nspname"
    static func tables(schema: String) -> String {
        """
        SELECT c.relname, CASE WHEN c.relkind IN ('r','p') THEN 'BASE TABLE' ELSE 'VIEW' END,
          'postgresql', GREATEST(c.reltuples,0)::bigint::text
        FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
        WHERE n.nspname=\(literal(schema)) AND c.relkind IN ('r','p','v','m') ORDER BY c.relname
        """
    }
    static func metadata(schema: String, table: String) -> String {
        let relation = literal(qualified(schema, table)) + "::regclass"
        return """
            SELECT a.attname, format_type(a.atttypid,a.atttypmod), CASE WHEN a.attnotnull THEN 'NO' ELSE 'YES' END,
              CASE WHEN EXISTS(SELECT 1 FROM pg_index i WHERE i.indrelid=a.attrelid AND i.indisprimary AND a.attnum=ANY(i.indkey))
                THEN 'PRI' ELSE '' END, pg_get_expr(d.adbin,d.adrelid),
              CASE WHEN a.attgenerated<>'' THEN 'GENERATED' WHEN a.attidentity='a' THEN 'IDENTITY ALWAYS auto_increment' WHEN a.attidentity='d' THEN 'IDENTITY DEFAULT auto_increment' WHEN pg_get_expr(d.adbin,d.adrelid) LIKE 'nextval(%'
                THEN 'auto_increment' ELSE '' END, COALESCE(co.collname,''), COALESCE(col_description(a.attrelid,a.attnum),'')
            FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid=a.attrelid AND d.adnum=a.attnum
              LEFT JOIN pg_collation co ON co.oid=a.attcollation
            WHERE a.attrelid=\(relation) AND a.attnum>0 AND NOT a.attisdropped ORDER BY a.attnum;
            SELECT 'definition', 'CREATE TABLE '||\(literal(qualified(schema, table)))|| E' (\\n' ||
              string_agg(quote_ident(a.attname)||' '||format_type(a.atttypid,a.atttypmod)||
                CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END ||
                CASE WHEN a.attidentity='a' THEN ' GENERATED ALWAYS AS IDENTITY'
                     WHEN a.attidentity='d' THEN ' GENERATED BY DEFAULT AS IDENTITY'
                     WHEN a.attgenerated<>'' THEN ' GENERATED ALWAYS AS ('||pg_get_expr(d.adbin,d.adrelid)||') '||CASE WHEN a.attgenerated='v' THEN 'VIRTUAL' ELSE 'STORED' END
                     WHEN d.adbin IS NOT NULL THEN ' DEFAULT '||pg_get_expr(d.adbin,d.adrelid) ELSE '' END, E',\\n' ORDER BY a.attnum)
              || COALESCE((SELECT E',\\n' || string_agg('CONSTRAINT '||quote_ident(con.conname)||' '||pg_get_constraintdef(con.oid,true),
                   E',\\n' ORDER BY con.conname) FROM pg_constraint con WHERE con.conrelid=\(relation)
                     AND con.contype IN ('p','u','f','c','x')), '')
              || E'\\n);' FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid=a.attrelid AND d.adnum=a.attnum
              WHERE a.attrelid=\(relation) AND a.attnum>0 AND NOT a.attisdropped;
            SELECT ci.relname AS index_name, pg_get_indexdef(i.indexrelid) AS definition,
              i.indisunique AS "unique", i.indisprimary AS "primary",
              EXISTS(SELECT 1 FROM pg_constraint con WHERE con.conindid=i.indexrelid AND con.contype IN ('p','u','x')) AS constraint_index
              FROM pg_index i JOIN pg_class ci ON ci.oid=i.indexrelid
              WHERE i.indrelid=\(relation) ORDER BY ci.relname;
            SELECT con.conname AS CONSTRAINT_NAME, local.attname AS COLUMN_NAME, current_database() AS REFERENCED_TABLE_SCHEMA,
              foreign_table.relname AS REFERENCED_TABLE_NAME, remote.attname AS REFERENCED_COLUMN_NAME,
              keys.ordinality::text AS ORDINAL_POSITION, foreign_schema.nspname AS referenced_schema
            FROM pg_constraint con CROSS JOIN LATERAL unnest(con.conkey,con.confkey) WITH ORDINALITY AS keys(local_key,remote_key,ordinality)
              JOIN pg_attribute local ON local.attrelid=con.conrelid AND local.attnum=keys.local_key
              JOIN pg_attribute remote ON remote.attrelid=con.confrelid AND remote.attnum=keys.remote_key
              JOIN pg_class foreign_table ON foreign_table.oid=con.confrelid
              JOIN pg_namespace foreign_schema ON foreign_schema.oid=foreign_table.relnamespace
            WHERE con.conrelid=\(relation) AND con.contype='f' ORDER BY con.conname,keys.ordinality;
            SELECT conname AS name,CASE contype WHEN 'p' THEN 'primary key' WHEN 'u' THEN 'unique' WHEN 'f' THEN 'foreign key'
              WHEN 'c' THEN 'check' WHEN 'n' THEN 'not null' WHEN 'x' THEN 'exclusion' ELSE 'constraint' END AS kind,pg_get_constraintdef(oid,true) AS definition
              FROM pg_constraint WHERE conrelid=\(relation) ORDER BY conname;
            """
    }

    static func rowPlan(
        location: DatabaseLocation, table: String, columns: [DatabaseColumn], draft: RowDraft,
        deleting: Bool = false
    ) throws -> SQLPlan {
        let target = qualified(location.schema, table)
        var parameters = [String?]()
        func parameter(_ value: CellDraft, column: DatabaseColumn) throws -> String {
            if value.mode == .omitted { return "DEFAULT" }
            if value.mode == .null {
                guard column.nullable || deleting else {
                    throw DatabaseError.message(column.name + " does not allow null")
                }
                parameters.append(nil)
            } else if column.binary {
                let hex = value.text.hasPrefix("0x") ? String(value.text.dropFirst(2)) : value.text
                guard Data(hex: hex) != nil else {
                    throw DatabaseError.message(column.name + ": enter hexadecimal bytes")
                }
                parameters.append("\\x" + hex)
            } else {
                parameters.append(value.text)
            }
            return "$\(parameters.count)"
        }
        let statement: String
        if let original = draft.original {
            let keys = columns.enumerated().filter { $0.element.key == "PRI" }
            guard original.count == columns.count, !keys.isEmpty, let revision = draft.rowVersion else {
                throw DatabaseError.message(
                    "refresh the table before editing; a primary key and row version are required")
            }
            var changes = [String]()
            if !deleting {
                for column in columns where !column.generated {
                    guard let value = draft.values[column.name], let index = columns.firstIndex(of: column) else {
                        continue
                    }
                    if value.mode == .value && original[index].hex != nil
                        && value.text == original[index].display(binary: column.binary) {
                        continue
                    }
                    if value.mode == .null && original[index].hex == nil { continue }
                    changes.append(identifier(column.name) + " = " + (try parameter(value, column: column)))
                }
                guard !changes.isEmpty else { throw DatabaseError.message("no values changed") }
            }
            var predicate = try keys.map { index, column in
                identifier(column.name) + " IS NOT DISTINCT FROM "
                    + (try parameter(
                        .init(
                            text: original[index].display(binary: column.binary),
                            mode: original[index].hex == nil ? .null : .value),
                        column: column))
            }
            parameters.append(revision)
            predicate.append("xmin::text = $\(parameters.count)")
            statement =
                (deleting ? "DELETE FROM " + target : "UPDATE " + target + " SET " + changes.joined(separator: ", "))
                + " WHERE " + predicate.joined(separator: " AND ")
        } else {
            let included = columns.filter { !$0.generated && draft.values[$0.name]?.mode != .omitted }
            let values = try included.map {
                try parameter(draft.values[$0.name] ?? .init(text: "", mode: .null), column: $0)
            }
            statement =
                "INSERT INTO " + target
                + (included.isEmpty
                    ? " DEFAULT VALUES"
                    : " (" + included.map { identifier($0.name) }.joined(separator: ", ") + ") VALUES ("
                        + values.joined(separator: ", ") + ")")
        }
        return .init(
            title: deleting ? "delete row" : "save row", sql: statement, database: location.database,
            oneRow: true, destructive: deleting, summary: location.database + "." + location.schema + "." + table,
            parameters: parameters)
    }
}
