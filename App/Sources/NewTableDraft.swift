import Foundation

struct NewTableColumn: Identifiable {
    let id = UUID()
    var name = ""
    var type = "varchar"
    var size = "255"
    var nullable = false
    var primary = false
    var autoIncrement = false
    var unsigned = false
    var hasSize: Bool {
        [
            "varchar", "char", "varbinary", "binary", "decimal", "numeric", "bit", "varbit",
            "time", "timetz", "timestamp", "timestamptz",
        ].contains(type)
    }
    static var identity: NewTableColumn {
        .init(name: "id", type: "bigint", size: "", primary: true, autoIncrement: true, unsigned: true)
    }
}
struct NewTableDraft {
    var name = ""
    var columns: [NewTableColumn] = [.identity]
    func plan(database: String, engine: DatabaseEngine = .mariadb, schema: String = "public") throws -> SQLPlan {
        if engine.isPostgreSQL {
            guard !name.isEmpty, name.utf8.count <= 63, !name.contains("\0"), !columns.isEmpty else {
                throw DatabaseError.message("enter a table name up to 63 bytes and add columns")
            }
            var names = Set<String>()
            var definitions = [String]()
            for column in columns {
                guard !column.name.isEmpty, column.name.utf8.count <= 63, !column.name.contains("\0"),
                    names.insert(column.name).inserted
                else { throw DatabaseError.message("column names must be unique") }
                var type = PostgreSQLColumnDraft()
                type.type =
                    ["int": "integer", "double": "double precision", "datetime": "timestamp"][column.type]
                    ?? column.type
                type.size = column.hasSize ? column.size : ""
                guard !column.autoIncrement || ["smallint", "integer", "bigint"].contains(type.type) else {
                    throw DatabaseError.message("identity requires a smallint, integer or bigint column")
                }
                definitions.append(
                    PostgreSQLSQL.identifier(column.name) + " " + (try type.validatedType())
                        + (column.autoIncrement ? " GENERATED BY DEFAULT AS IDENTITY" : "")
                        + (column.nullable && !column.primary ? "" : " NOT NULL"))
            }
            let primary = columns.filter(\.primary).map { PostgreSQLSQL.identifier($0.name) }
            if !primary.isEmpty { definitions.append("PRIMARY KEY (" + primary.joined(separator: ", ") + ")") }
            return .init(
                title: "create table",
                sql: "CREATE TABLE " + PostgreSQLSQL.qualified(schema, name)
                    + " (" + definitions.joined(separator: ", ") + ")", database: database)
        }
        let table = name.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !table.isEmpty, table.utf8.count <= 64, !table.contains("\0"), !table.contains("/") else {
            throw DatabaseError.message("enter a table name up to 64 bytes")
        }
        guard !columns.isEmpty else { throw DatabaseError.message("add at least one column") }
        var names = Set<String>(), definitions = [String]()
        guard columns.filter(\.autoIncrement).count <= 1 else {
            throw DatabaseError.message("only one column may use auto increment")
        }
        for column in columns {
            let name = column.name.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !name.isEmpty, name.utf8.count <= 64, !name.contains("\0"), names.insert(name.lowercased()).inserted
            else {
                throw DatabaseError.message("column names must be unique and up to 64 bytes")
            }
            var editor = ColumnEditorDraft(original: nil, name: name, definition: "varchar(255) NOT NULL")
            editor.typeName = column.type
            editor.parameters = column.hasSize ? column.size : ""
            editor.nullable = column.nullable && !column.primary
            editor.unsigned = column.unsigned
            editor.autoIncrement = column.autoIncrement
            guard !column.autoIncrement || (column.primary && editor.integer) else {
                throw DatabaseError.message("auto increment requires an integer primary key")
            }
            definitions.append(DatabaseSQL.identifier(name) + " " + (try editor.builtDefinition()))
        }
        let primary = columns.filter(\.primary).map {
            DatabaseSQL.identifier($0.name.trimmingCharacters(in: .whitespaces))
        }
        if !primary.isEmpty { definitions.append("PRIMARY KEY (" + primary.joined(separator: ", ") + ")") }
        return .init(
            title: "create table",
            sql: "CREATE TABLE \(DatabaseSQL.qualified(database, table)) (\n"
                + definitions.joined(separator: ",\n") + "\n) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;",
            database: database)
    }
}
